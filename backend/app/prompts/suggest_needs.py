def build_messages(text: str, labels: dict) -> list[dict]:
    menu = "\n".join(f"{code}: {label}" for code, label in labels.items())
    return [{"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": f"รายการ:\n{menu}\n\nข้อความ: {text}\n\nผลลัพธ์:"}]
