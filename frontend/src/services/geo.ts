const clean = (s?: string | null) => (s || '').replace(/^(เขต|อำเภอ|อ\.)\s*/, '').trim();

export function approxLatLng(province?: string | null, district?: string | null): { lat: number; lng: number } | null {
  const p = clean(province).replace(/^จังหวัด/, '');
  const d = clean(district);
  const hit = (p === 'กรุงเทพมหานคร' || p === 'กรุงเทพ' || !p) && BANGKOK[d] ? BANGKOK[d] : PROVINCES[p];
  return hit ? { lat: hit[0], lng: hit[1] } : null;
}
